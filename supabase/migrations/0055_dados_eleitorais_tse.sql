  using (true);

drop policy if exists "eleicao_votos_municipio grava" on public.eleicao_votos_municipio;
create policy "eleicao_votos_municipio grava" on public.eleicao_votos_municipio
  for all to authenticated
  using ((select public.perfil_equipe()))
  with check ((select public.perfil_equipe()));

grant select on public.eleicao_votos_municipio to anon, authenticated, service_role;
grant insert, update, delete on public.eleicao_votos_municipio to authenticated, service_role;


-- 3. DETALHAMENTO DE VOTOS (BAIRRO / ZONA / LOCAL DE VOTAÇÃO / ESCOLAS)
-- Guardado apenas para municípios-foco da campanha.
create table if not exists public.eleicao_votos_detalhe (
  id            bigint generated by default as identity primary key,
  candidato_id  bigint not null references public.eleicao_candidatos(id) on delete cascade,
  ano           integer not null,
  turno         smallint not null default 1,
  uf            text not null,
  municipio     text not null,
  zona          integer not null,
  secao         integer,
  local_votacao text,
  bairro        text,
  votos         integer not null check (votos >= 0),
  atualizado_em timestamptz not null default now()
);

comment on table public.eleicao_votos_detalhe is
  'Votação granular até o colégio eleitoral/bairro para municípios estratégicos da campanha.';

create index if not exists idx_eleicao_votos_det_cand_mun
  on public.eleicao_votos_detalhe (candidato_id, municipio);

create index if not exists idx_eleicao_votos_det_mun_bairro
  on public.eleicao_votos_detalhe (municipio, bairro);

alter table public.eleicao_votos_detalhe enable row level security;

