-- ============================================================================
-- DADOS ELEITORAIS DO TSE — ESTRUTURA NACIONAL DE VOTAÇÃO
-- ============================================================================
--
-- Armazena os dados consolidados do TSE (2022, 2024, 2026) a nível Brasil:
--   1. Candidatos e metadados (nome, cargo, partido, número, foto)
--   2. Votos consolidados por município (5.570 municípios, leve e instantâneo)
--   3. Detalhamento por bairro/zona/local de votação apenas para cidades-foco
--
-- ────────────────────────────────────────────────────────────────────────────

-- 1. CADASTRO DE CANDIDATOS
create table if not exists public.eleicao_candidatos (
  id              bigint generated by default as identity primary key,
  ano             integer not null check (ano >= 2000),
  turno           smallint not null default 1 check (turno in (1, 2)),
  uf              text not null, -- 'BA', 'SP', 'BR' (nacional)
  cargo           text not null, -- 'DEPUTADO FEDERAL', 'DEPUTADO ESTADUAL', 'PREFEITO', etc.
  numero          integer not null,
  sq_candidato    text, -- Sequencial único oficial do TSE
  nome_urna       text not null,
  nome_completo   text,
  partido_sigla   text not null,
  partido_numero  integer,
  coligacao       text,
  situacao        text, -- 'ELEITO', 'SUPLENTE', 'NÃO ELEITO', etc.
  foto_url        text,
  chave_busca     text, -- Texto desacentuado para busca rápida no autocomplete
  atualizado_em   timestamptz not null default now(),
  unique (ano, turno, uf, cargo, numero)
);

comment on table public.eleicao_candidatos is
  'Dicionário oficial de candidatos do TSE para qualquer pleito nacional ou estadual.';

create index if not exists idx_eleicao_candidatos_busca
  on public.eleicao_candidatos (ano, uf, cargo, numero);

create index if not exists idx_eleicao_candidatos_chave
  on public.eleicao_candidatos using gin (to_tsvector('portuguese', coalesce(chave_busca, nome_urna)));

alter table public.eleicao_candidatos enable row level security;

drop policy if exists "eleicao_candidatos le" on public.eleicao_candidatos;
create policy "eleicao_candidatos le" on public.eleicao_candidatos
  for select to authenticated, anon
  using (true);

drop policy if exists "eleicao_candidatos grava" on public.eleicao_candidatos;
create policy "eleicao_candidatos grava" on public.eleicao_candidatos
  for all to authenticated
  using ((select public.perfil_equipe()))
  with check ((select public.perfil_equipe()));

grant select on public.eleicao_candidatos to anon, authenticated, service_role;
grant insert, update, delete on public.eleicao_candidatos to authenticated, service_role;


-- 2. VOTAÇÃO POR MUNICÍPIO (NÍVEL BRASIL CONSOLIDADO)
create table if not exists public.eleicao_votos_municipio (
  id            bigint generated by default as identity primary key,
  candidato_id  bigint not null references public.eleicao_candidatos(id) on delete cascade,
  ano           integer not null,
  turno         smallint not null default 1,
  uf            text not null,
  municipio     text not null,
  codigo_tse    text, -- Código do município na base do TSE
  votos         integer not null check (votos >= 0),
  atualizado_em timestamptz not null default now(),
  unique (candidato_id, codigo_tse, municipio)
);

comment on table public.eleicao_votos_municipio is
  'Votação consolidada de cada candidato em cada município brasileiro. Leve, rápido e escalável.';

create index if not exists idx_eleicao_votos_mun_cand
  on public.eleicao_votos_municipio (candidato_id, votos desc);

create index if not exists idx_eleicao_votos_mun_uf
  on public.eleicao_votos_municipio (ano, uf, municipio);

alter table public.eleicao_votos_municipio enable row level security;

drop policy if exists "eleicao_votos_municipio le" on public.eleicao_votos_municipio;
create policy "eleicao_votos_municipio le" on public.eleicao_votos_municipio
