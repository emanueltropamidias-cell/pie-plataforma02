-- ============================================================================
-- CAMADA 3 (MUNICÍPIO) PARA QUALQUER CANDIDATO, NÃO SÓ A TALITA
-- ============================================================================
--
-- Ao abrir Salvador com outro candidato na tela, o painel mostrava as zonas e
-- os bairros DA TALITA EM 2022: eles vinham de `votos-zonas.ts` e
-- `votos_bairro`, que só têm a votação dela. Nada avisava.
--
-- Agora a camada municipal lê do banco, por candidato:
--
--   eleicao_votos_zona     todo candidato, toda cidade, por zona eleitoral.
--                          Sai do mesmo arquivo do TSE dos votos por
--                          município (votacao_candidato_munzona).
--
--   eleicao_votos_detalhe  (já existia, vazia) por LOCAL de votação, com o
--                          bairro do local, só para as cidades-foco. Sai do
--                          voto por seção + cadastro de locais do TSE
--                          (scripts/importar-tse-locais.mjs). Grande demais
--                          para o estado inteiro.
-- ────────────────────────────────────────────────────────────────────────────

create table if not exists public.eleicao_votos_zona (
  id            bigint generated by default as identity primary key,
  candidato_id  bigint not null references public.eleicao_candidatos(id) on delete cascade,
  codigo_tse    text not null,
  municipio     text not null,
  zona          integer not null,
  votos         integer not null check (votos >= 0),
  unique (candidato_id, codigo_tse, zona)
);

comment on table public.eleicao_votos_zona is
  'Votação de cada candidato por zona eleitoral em cada município (TSE, votacao_candidato_munzona).';

alter table public.eleicao_votos_zona enable row level security;
drop policy if exists "eleicao_votos_zona le" on public.eleicao_votos_zona;
create policy "eleicao_votos_zona le" on public.eleicao_votos_zona
  for select to authenticated using (true);
grant select on public.eleicao_votos_zona to authenticated, service_role;

-- Detalhe por local: um registro por candidato e local de votação. `secao`
-- fica nula — guardar seção multiplicaria as linhas por ~10 sem a tela usar.
alter table public.eleicao_votos_detalhe add column if not exists codigo_tse text;
alter table public.eleicao_votos_detalhe add column if not exists nr_local integer;
create unique index if not exists eleicao_votos_detalhe_local_key
  on public.eleicao_votos_detalhe (candidato_id, codigo_tse, zona, nr_local);

-- Tudo o que a camada municipal mostra, de um candidato numa cidade.
create or replace function public.obter_detalhe_municipio(p_candidato_id bigint, p_municipio text)
returns jsonb
language sql
stable
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'zonas', coalesce((
      select jsonb_agg(jsonb_build_object('zona', zona, 'votos', votos) order by votos desc)
        from public.eleicao_votos_zona
       where candidato_id = p_candidato_id and municipio = p_municipio
    ), '[]'::jsonb),
    -- null = cidade sem detalhe importado. Diferente de lista vazia, que é
    -- "importado, e o candidato não teve voto em local nenhum".
    'locais', (
      select jsonb_agg(jsonb_build_object(
               'zona', zona, 'local', local_votacao, 'bairro', bairro, 'votos', votos)
             order by votos desc)
        from public.eleicao_votos_detalhe
       where candidato_id = p_candidato_id and municipio = p_municipio and votos > 0
    ),
    'tem_detalhe', exists (
      select 1 from public.eleicao_votos_detalhe d
        join public.eleicao_candidatos c on c.id = d.candidato_id
        join public.eleicao_candidatos e on e.id = p_candidato_id
       where d.municipio = p_municipio and c.ano = e.ano
       limit 1
    )
  );
$$;

grant execute on function public.obter_detalhe_municipio(bigint, text) to authenticated, service_role;

-- O mais votado de uma eleição, para a tela abrir em alguém quando se troca
-- de ano ou de cargo. 1º turno: é onde todo mundo concorre.
create or replace function public.eleicao_destaque(p_ano integer, p_uf text, p_cargo text default null)
returns bigint
language sql
stable
set search_path = public, pg_temp
as $$
  select c.id
    from public.eleicao_candidatos c
    join public.eleicao_votos_municipio v on v.candidato_id = c.id
   where c.ano = p_ano and c.uf = p_uf and c.turno = 1
     and (p_cargo is null or c.cargo = p_cargo)
   group by c.id
   order by sum(v.votos) desc
   limit 1;
$$;

grant execute on function public.eleicao_destaque(integer, text, text) to authenticated, service_role;

-- ── conferência ─────────────────────────────────────────────────────────────
select 2024 as ano, (select nome_urna from public.eleicao_candidatos where id = public.eleicao_destaque(2024, 'BA')) as destaque
union all
select 2026, (select nome_urna from public.eleicao_candidatos where id = public.eleicao_destaque(2026, 'BA', 'DEPUTADO FEDERAL'));
