-- ============================================================================
-- A VOTAÇÃO DO CANDIDATO SAI DO CÓDIGO E VIRA DADO
-- ============================================================================
--
-- Rode inteiro. Pode rodar de novo sem medo.
--
-- ── O PROBLEMA ──────────────────────────────────────────────────────────────
--
-- A votação de 2022 estava escrita DENTRO do código, em `src/lib/votos-talita.ts`
-- — 415 municípios em TypeScript. Enquanto havia uma campanha só, era apenas
-- feio. Com duas instalações rodando do MESMO repositório, virou defeito:
--
--   a plataforma do Manassés abria mostrando o mapa de cobertura DELA,
--   as metas DELA, o total de votos DELA — com o banco dele vazio
--
-- Nada no banco estava errado. O número nunca foi dado: era código.
--
-- ── POR QUE UMA TABELA NOVA, E NÃO A `candidato_votos` ──────────────────────
--
-- Aquela guarda a votação dos PARCEIROS de dobradinha, e aponta para
-- `candidatos_dobradinha`. O candidato da casa não é parceiro de si mesmo:
-- enfiá-lo lá obrigaria a criar uma linha dele em "dobradinha" e todo lugar que
-- lista parceiros passaria a mostrá-lo junto.
--
-- Aqui é o dono da instalação. Uma linha por município, e pronto.

create table if not exists public.votos_candidato (
  id            bigint generated by default as identity primary key,
  -- Grafia OFICIAL, a mesma de `municipios_ba`. Sem isso o mapa não pinta e
  -- ninguém descobre por quê: município que não casa some sem erro.
  municipio     text    not null,
  votos         integer not null default 0 check (votos >= 0),
  -- O ano deixa a base servir para a eleição seguinte sem apagar a anterior —
  -- e comparar 2022 com 2026 é metade do valor de ter isto guardado.
  eleicao       integer not null default 2022,
  atualizado_em timestamptz not null default now(),
  atualizado_por uuid,
  unique (municipio, eleicao)
);

comment on table public.votos_candidato is
  'A votação do candidato DESTA instalação, por município. Antes vivia dentro do código, o que fazia a plataforma de um candidato mostrar os votos do outro.';

create index if not exists votos_candidato_por_eleicao
  on public.votos_candidato (eleicao, votos desc);

alter table public.votos_candidato enable row level security;

-- Leitura para a equipe; escrita só para quem manda. Votação é o número que
-- sustenta toda a estratégia — não é campo que atendente mexe sem querer.
drop policy if exists "votos_candidato le" on public.votos_candidato;
create policy "votos_candidato le" on public.votos_candidato
  for select to authenticated
  using ((select public.perfil_atendimento()));

drop policy if exists "votos_candidato mexe" on public.votos_candidato;
create policy "votos_candidato mexe" on public.votos_candidato
  for all to authenticated
  using ((select public.perfil_equipe()))
  with check ((select public.perfil_equipe()));

grant select on public.votos_candidato to anon, authenticated, service_role;
grant insert, update, delete on public.votos_candidato to authenticated, service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- O PLACAR DA COBERTURA
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Devolve tudo que as telas de mapa, dashboard e estratégia precisam, numa
-- consulta só. Elas faziam essa conta em TypeScript sobre o arquivo fixo.
create or replace function public.votos_por_municipio(p_eleicao integer default 2022)
returns jsonb
language sql
stable
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'eleicao',    p_eleicao,
    'total',      coalesce((select sum(votos) from public.votos_candidato where eleicao = p_eleicao), 0),
    'municipios', coalesce((select count(*) from public.votos_candidato where eleicao = p_eleicao), 0),
    'por_municipio', coalesce(
      (select jsonb_object_agg(municipio, votos)
         from public.votos_candidato where eleicao = p_eleicao), '{}'::jsonb)
  );
$$;

comment on function public.votos_por_municipio is
  'A votação do candidato desta instalação: total, quantos municípios e o mapa município -> votos.';

-- ── conferência ─────────────────────────────────────────────────────────────
select (public.votos_por_municipio() ->> 'total')      as total_de_votos,
       (public.votos_por_municipio() ->> 'municipios') as municipios_com_voto;
