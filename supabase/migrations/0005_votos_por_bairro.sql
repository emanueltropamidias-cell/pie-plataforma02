-- ============================================================================
-- A VOTAÇÃO POR BAIRRO SAI DO CÓDIGO
-- ============================================================================
--
-- Rode inteiro. Pode rodar de novo sem medo.
--
-- ── O MESMO DEFEITO DOS VOTOS POR MUNICÍPIO ─────────────────────────────────
--
-- `src/lib/votos-bairros.ts` guarda os 146 bairros de Salvador com a votação da
-- Talita. Como as duas instalações compartilham o repositório, a tela de
-- estratégia do Manassés mostrava os bairros DELA.
--
-- ── A CONFERÊNCIA QUE VALIDA ESTE DADO ──────────────────────────────────────
--
-- A soma dos bairros tem de bater com o total do município, voto a voto:
--
--   Talita     146 bairros -> 5.720   = VOTOS_TALITA["Salvador"]
--   Manassés   145 bairros -> 5.314   = o Salvador dele
--
-- Bateu nos dois. Voto nenhum sumiu e nenhum foi contado duas vezes.
--
-- ── O QUE ESSA CONFERÊNCIA NÃO PROVA ────────────────────────────────────────
--
-- Que a cidade toda está aqui. Salvador tem 163 bairros na malha oficial, e as
-- listas citam ~146 nomes. A fonte usa um vocabulário mais grosso que a malha —
-- o mesmo que produz "CAJAZEIRAS" sem número e "CASTELO BRANCO (1A ETAPA)" — e
-- o voto de quem não está no vocabulário cai no vizinho que está. Isso mantém o
-- total certo e erra a atribuição, inflando quem consta.
--
-- Na lista do Manassés, PERIPERI vinha DUAS VEZES (39 e 26), de zonas
-- eleitorais diferentes. Ficaram somados em 65: o mapa desenha um polígono por
-- bairro, e um nome inventado tipo "PERIPERI 2" não casaria com polígono nenhum
-- e sumiria do mapa sem erro.

create table if not exists public.votos_bairro (
  id         bigint generated by default as identity primary key,
  -- Grafia oficial do município, a mesma de `municipios_ba`.
  municipio  text    not null,
  -- Nome do bairro COMO VEIO da apuração, em caixa alta. A normalização para
  -- comparar acontece na leitura, e não no dado guardado: guardar já
  -- normalizado perde a grafia original e não dá para conferir depois.
  bairro     text    not null,
  votos      integer not null default 0 check (votos >= 0),
  eleicao    integer not null default 2022,
  atualizado_em timestamptz not null default now(),
  unique (municipio, bairro, eleicao)
);

comment on table public.votos_bairro is
  'Votação por bairro do candidato DESTA instalação. A soma por município tem de bater com votos_candidato — é o que prova que nenhum voto sumiu.';

create index if not exists votos_bairro_por_municipio
  on public.votos_bairro (municipio, eleicao, votos desc);

alter table public.votos_bairro enable row level security;

drop policy if exists "votos_bairro le" on public.votos_bairro;
create policy "votos_bairro le" on public.votos_bairro
  for select to authenticated
  using ((select public.perfil_atendimento()));

drop policy if exists "votos_bairro mexe" on public.votos_bairro;
create policy "votos_bairro mexe" on public.votos_bairro
  for all to authenticated
  using ((select public.perfil_equipe()))
  with check ((select public.perfil_equipe()));

grant select on public.votos_bairro to anon, authenticated, service_role;
grant insert, update, delete on public.votos_bairro to authenticated, service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- OS BAIRROS, E A PROVA DE QUE FECHAM
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Devolve os bairros junto com a conferência: o total do município pelos
-- bairros e o total por `votos_candidato`. Os dois lado a lado, porque número
-- que não fecha tem de aparecer na mesma tela em que se olha o dado — e não
-- num relatório que ninguém abre.
create or replace function public.votos_por_bairro(
  p_municipio text default 'Salvador',
  p_eleicao   integer default 2022
)
returns jsonb
language sql
stable
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'municipio', p_municipio,
    'eleicao',   p_eleicao,
    'total_pelos_bairros', coalesce(
      (select sum(votos) from public.votos_bairro
        where municipio = p_municipio and eleicao = p_eleicao), 0),
    'total_do_municipio', coalesce(
      (select votos from public.votos_candidato
        where municipio = p_municipio and eleicao = p_eleicao), 0),
    'bairros', coalesce(
      (select jsonb_object_agg(bairro, votos)
         from public.votos_bairro
        where municipio = p_municipio and eleicao = p_eleicao), '{}'::jsonb)
  );
$$;

comment on function public.votos_por_bairro is
  'Os bairros do município e a conferência: soma pelos bairros contra o total do município. Os dois juntos, porque número que não fecha tem de aparecer onde se olha o dado.';

-- ── conferência ─────────────────────────────────────────────────────────────
select (public.votos_por_bairro() ->> 'total_pelos_bairros') as pelos_bairros,
       (public.votos_por_bairro() ->> 'total_do_municipio')  as do_municipio,
       case when (public.votos_por_bairro() ->> 'total_pelos_bairros')
               = (public.votos_por_bairro() ->> 'total_do_municipio')
            then 'fecha' else 'NAO FECHA' end as conferencia;
