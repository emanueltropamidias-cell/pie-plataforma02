-- Estrutura para inteligência eleitoral comparativa de eleições.
-- Permite analisar o desempenho histórico e planejar cenários para 2026.

create table if not exists public.tse_eleicoes (
  ano           integer primary key,
  descricao     text not null,
  tipo          text not null check (tipo in ('geral', 'municipal')),
  data_pleito   date,
  total_aptos   bigint default 0
);

comment on table public.tse_eleicoes is 'Eleições cadastradas no módulo de inteligência eleitoral.';

create table if not exists public.tse_candidatos (
  id            bigint generated by default as identity primary key,
  ano           integer not null references public.tse_eleicoes(ano),
  cargo         text not null,
  municipio     text not null default 'Bahia (Geral)',
  uf            text not null default 'BA',
  numero        text not null,
  nome_urna     text not null,
  nome_completo text,
  partido       text not null,
  sigla_partido text not null,
  coligacao     text,
  situacao      text not null default 'Não eleito',
  total_votos   bigint not null default 0 check (total_votos >= 0),
  percentual    numeric(6, 2) default 0,
  foto_url      text,
  atualizado_em timestamptz not null default now()
);

create index if not exists idx_tse_candidatos_busca
  on public.tse_candidatos (ano, cargo, total_votos desc);

create index if not exists idx_tse_candidatos_partido
  on public.tse_candidatos (ano, sigla_partido);

create table if not exists public.tse_votos_municipio (
  id                  bigint generated by default as identity primary key,
  ano                 integer not null references public.tse_eleicoes(ano),
  cargo               text not null,
  municipio           text not null,
  candidato_numero    text not null,
  candidato_nome      text not null,
  sigla_partido       text not null,
  votos               integer not null default 0 check (votos >= 0),
  total_aptos         integer default 0,
  total_validos       integer default 0,
  percentual_valido   numeric(6, 2) default 0,
  unique (ano, cargo, municipio, candidato_numero)
);

create index if not exists idx_tse_votos_municipio_busca
  on public.tse_votos_municipio (ano, municipio, votos desc);

create table if not exists public.tse_projecoes_2026 (
  id                  bigint generated by default as identity primary key,
  cargo               text not null,
  uf                  text not null default 'BA',
  quociente_estimado  bigint not null,
  vagas_totais        integer not null,
  partido_federacao   text not null,
  votos_estimados     bigint not null default 0,
  cadeiras_provaveis  integer not null default 0,
  corte_partidario    bigint default 0,
  analise_cenario     text
);

-- RLS
alter table public.tse_eleicoes enable row level security;
alter table public.tse_candidatos enable row level security;
alter table public.tse_votos_municipio enable row level security;
alter table public.tse_projecoes_2026 enable row level security;

-- Leitura pública para usuários autenticados da plataforma
drop policy if exists "tse_eleicoes_le" on public.tse_eleicoes;
create policy "tse_eleicoes_le" on public.tse_eleicoes for select to authenticated using (true);

drop policy if exists "tse_candidatos_le" on public.tse_candidatos;
create policy "tse_candidatos_le" on public.tse_candidatos for select to authenticated using (true);

drop policy if exists "tse_votos_municipio_le" on public.tse_votos_municipio;
create policy "tse_votos_municipio_le" on public.tse_votos_municipio for select to authenticated using (true);

drop policy if exists "tse_projecoes_2026_le" on public.tse_projecoes_2026;
create policy "tse_projecoes_2026_le" on public.tse_projecoes_2026 for select to authenticated using (true);

-- Permissões de escrita para a equipe
drop policy if exists "tse_candidatos_mexe" on public.tse_candidatos;
create policy "tse_candidatos_mexe" on public.tse_candidatos for all to authenticated using ((select public.perfil_equipe())) with check ((select public.perfil_equipe()));

drop policy if exists "tse_votos_municipio_mexe" on public.tse_votos_municipio;
create policy "tse_votos_municipio_mexe" on public.tse_votos_municipio for all to authenticated using ((select public.perfil_equipe())) with check ((select public.perfil_equipe()));

drop policy if exists "tse_projecoes_2026_mexe" on public.tse_projecoes_2026;
create policy "tse_projecoes_2026_mexe" on public.tse_projecoes_2026 for all to authenticated using ((select public.perfil_equipe())) with check ((select public.perfil_equipe()));

grant select on public.tse_eleicoes, public.tse_candidatos, public.tse_votos_municipio, public.tse_projecoes_2026 to anon, authenticated, service_role;
grant insert, update, delete on public.tse_eleicoes, public.tse_candidatos, public.tse_votos_municipio, public.tse_projecoes_2026 to authenticated, service_role;

