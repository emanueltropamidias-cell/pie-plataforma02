-- ============================================================================
-- A META POR MUNICÍPIO SAI DO CÓDIGO
-- ============================================================================
--
-- Rode inteiro. Pode rodar de novo sem medo.
--
-- ── O QUE ESTAVA ERRADO ─────────────────────────────────────────────────────
--
-- "A Raiz Continua" — triplicar a votação nos 15 maiores municípios — estava
-- escrita em `src/lib/raiz-continua.ts`, com os 15 municípios da Talita, os
-- votos dela de 2022 e a meta de 47.964.
--
-- É ESTRATÉGIA DELA, não régua do sistema. Mas, escrita no código que as duas
-- instalações compartilham, aparecia igual na plataforma do Manassés — com os
-- municípios dela e uma meta que não é dele.
--
-- ── POR QUE NÃO A `metas_campanha` ──────────────────────────────────────────
--
-- Aquela é de campanha de tráfego: `campanha`, `rotulo`, `meta`. Mede anúncio.
-- Esta é território: município, mesorregião, votação anterior e para onde se
-- quer levar. Juntar as duas na mesma tabela faria as telas filtrarem uma da
-- outra para sempre.
--
-- ── E POR QUE ELA PODE FICAR VAZIA ──────────────────────────────────────────
--
-- Instalação sem meta definida é o estado NORMAL de quem acabou de instalar,
-- não um defeito. A tela mostra que não há meta e oferece criar — em vez de
-- mostrar a meta de outra pessoa, que foi o que acontecia.

create table if not exists public.meta_municipio (
  id            bigint generated by default as identity primary key,
  -- Grafia oficial, a mesma de `municipios_ba`.
  municipio     text    not null,
  -- O agrupamento que a tela usa para somar por região.
  mesorregiao   text,
  -- De onde se parte. Fica GUARDADO aqui, e não lido de `votos_candidato`, de
  -- propósito: a meta foi feita com o número daquele dia, e se a base de votos
  -- for corrigida depois, a meta histórica não deve mudar sozinha por baixo.
  votos_base    integer not null default 0,
  -- Para onde se quer levar.
  meta          integer not null default 0 check (meta >= 0),
  eleicao       integer not null default 2026,
  criado_em     timestamptz not null default now(),
  unique (municipio, eleicao)
);

comment on table public.meta_municipio is
  'A meta de votos por município DESTA instalação. Vazia é estado normal de instalação nova — a tela oferece criar, em vez de mostrar a meta de outro candidato.';

alter table public.meta_municipio enable row level security;

drop policy if exists "meta_municipio le" on public.meta_municipio;
create policy "meta_municipio le" on public.meta_municipio
  for select to authenticated
  using ((select public.perfil_atendimento()));

drop policy if exists "meta_municipio mexe" on public.meta_municipio;
create policy "meta_municipio mexe" on public.meta_municipio
  for all to authenticated
  using ((select public.perfil_equipe()))
  with check ((select public.perfil_equipe()));

grant select on public.meta_municipio to anon, authenticated, service_role;
grant insert, update, delete on public.meta_municipio to authenticated, service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- O PLACAR DA META
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Devolve as cidades e o total. A tela fazia essa soma em TypeScript sobre o
-- arquivo fixo; agora ela só desenha o que vier — e desenha vazio quando não
-- houver meta, que é o comportamento certo numa instalação nova.
create or replace function public.placar_meta(p_eleicao integer default 2026)
returns jsonb
language sql
stable
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'eleicao', p_eleicao,
    'meta_total', coalesce((select sum(meta) from public.meta_municipio where eleicao = p_eleicao), 0),
    'base_total', coalesce((select sum(votos_base) from public.meta_municipio where eleicao = p_eleicao), 0),
    'cidades', coalesce((
      select jsonb_agg(jsonb_build_object(
               'municipio', m.municipio,
               'mesorregiao', m.mesorregiao,
               'votos_base', m.votos_base,
               'meta', m.meta
             ) order by m.meta desc, m.municipio)
        from public.meta_municipio m where m.eleicao = p_eleicao), '[]'::jsonb)
  );
$$;

comment on function public.placar_meta is
  'As cidades com meta desta instalação e os totais. Devolve lista vazia quando não há meta — e a tela precisa saber desenhar isso.';

-- ── conferência ─────────────────────────────────────────────────────────────
select (public.placar_meta() ->> 'meta_total') as meta_total,
       jsonb_array_length((public.placar_meta() -> 'cidades')) as cidades;
