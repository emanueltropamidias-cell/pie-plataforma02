// Votação de 2022 por zona eleitoral, seção e local de votação.
//
// Entra município por município, zona por zona, conforme sai do TSE. O que já
// está aqui é o que a plataforma pode afirmar; o resto ela declara ausente em
// vez de estimar.
//
// A coluna `share` dos LOCAIS é a fatia daquele local nos votos VÁLIDOS DA ZONA
// inteira — não a fatia da Talita dentro do local.
//
// Isto aqui já foi documentado ao contrário, e a própria tabela desmente: divida
// votos por share nos 26 locais da zona 12 e o resultado é sempre ~121 (a
// variação é só o arredondamento em duas casas). Razão constante quer dizer
// divisor único, e divisor único quer dizer zona, não local — para ser fatia do
// local, todos os 26 precisariam ter exatamente o mesmo número de votos válidos.
// O divisor implicado é 12.206, os válidos da zona 12; os 509 votos dela ali são
// 4,17% disso.
//
// A consequência prática: share ordena EXATAMENTE igual a votos, então não
// existe leitura de "força" separada do volume nesta coluna. Quem quiser força
// de verdade precisa dos válidos por local, que não estão aqui. Enquanto não
// estiverem, a tela diz o que a coluna é em vez de prometer o que ela não faz.

