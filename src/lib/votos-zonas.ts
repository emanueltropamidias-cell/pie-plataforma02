/** Zonas já importadas de um município, em ordem numérica. */
export function zonasDe(municipio: string): number[] {
  return Object.keys(VOTOS_ZONA[municipio] ?? {})
    .map(Number)
    .sort((a, b) => a - b);
}

/** Votos somados de uma zona — vale como conferência contra o total do TSE. */
export function totalDaZona(municipio: string, zona: number) {
  const z = VOTOS_ZONA[municipio]?.[zona];
  if (!z) return 0;
  return z.secoes.reduce((s, x) => s + x.votos, 0);
}
